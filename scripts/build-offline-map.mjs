#!/usr/bin/env node
// Builds the self-hosted offline basemap for the trail corridor. Run manually
// after scripts/build-trail.mjs (needs network + the `pmtiles` CLI from
// https://github.com/protomaps/go-pmtiles/releases):
//   PMTILES_BIN=/path/to/pmtiles node scripts/build-offline-map.mjs
//
// Why Protomaps and not the online OpenFreeMap tiles: OpenFreeMap's ToS forbids
// automated collection from their service, so we never bulk-cache their tiles.
// Protomaps publishes daily OSM builds and explicitly supports cutting a region
// out with `pmtiles extract` and hosting it yourself (ODbL, OSM attribution).
// Output goes to public/offline/ and is served from our own GitHub Pages.

import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync, statSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "public/offline");
const bin = process.env.PMTILES_BIN ?? "pmtiles";
const MAXZOOM = 15;
const ASSETS = "https://protomaps.github.io/basemaps-assets";
const FONTS = ["Noto Sans Regular", "Noto Sans Medium", "Noto Sans Italic"];
// Latin, Latin Extended-A (Turkish ı ğ ş İ), Cyrillic.
const RANGES = ["0-255", "256-511", "1024-1279"];

mkdirSync(out, { recursive: true });

// 1. Latest daily planet build.
const builds = await (await fetch("https://build-metadata.protomaps.dev/builds.json")).json();
const latest = builds.at(-1);
console.log(`Protomaps build ${latest.key} (v${latest.version})`);

// 2. Corridor extract.
execFileSync(bin, [
  "extract", `https://build.protomaps.com/${latest.key}`, path.join(out, "corridor.pmtiles"),
  `--region=${path.join(root, "data/corridor.geojson")}`, `--maxzoom=${MAXZOOM}`,
], { stdio: "inherit" });

// 3. Glyphs + sprites for the "light" flavor.
async function download(url, dest) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  mkdirSync(path.dirname(dest), { recursive: true });
  writeFileSync(dest, Buffer.from(await r.arrayBuffer()));
}
for (const font of FONTS) {
  for (const range of RANGES) {
    await download(`${ASSETS}/fonts/${encodeURIComponent(font)}/${range}.pbf`, path.join(out, "fonts", font, `${range}.pbf`));
  }
}
for (const f of ["light.json", "light.png", "light@2x.json", "light@2x.png"]) {
  await download(`${ASSETS}/sprites/v4/${f}`, path.join(out, "sprites", f));
}

// 4. Manifest: the app shows the exact download size before starting.
const files = [];
function walk(dir) {
  for (const name of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, name.name);
    if (name.isDirectory()) walk(full);
    else if (name.name !== "manifest.json") files.push({ path: path.relative(out, full).split(path.sep).join("/"), bytes: statSync(full).size });
  }
}
walk(out);
const totalBytes = files.reduce((s, f) => s + f.bytes, 0);
writeFileSync(path.join(out, "manifest.json"), JSON.stringify({
  _comment: "GENERATED by scripts/build-offline-map.mjs. Corridor ±2 km around the trail + Ölüdeniz hotel, Gelemiş, Kaş.",
  build: latest.key,
  maxzoom: MAXZOOM,
  generatedAt: new Date().toISOString().slice(0, 10),
  totalBytes,
  files,
}, null, 1));
console.log(`Offline map: ${files.length} files, ${(totalBytes / 1024 / 1024).toFixed(2)} MB`);
